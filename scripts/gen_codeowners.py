#!/usr/bin/env python3
"""Generate .github/CODEOWNERS from who submitted each spec.

Each draft under specs/ is owned by the GitHub user who submitted it: the
author of the pull request that first added any revision of the draft
(matched by draft name, not content similarity), or the commit author when
no pull request is found. DEFAULT_OWNERS are added to every entry, and own
/specs/ as a whole so a new draft has an owner before CODEOWNERS is
regenerated. DEFAULT_OWNERS also own POLICY_FILES (CODEOWNERS itself and
this generator), so the review policy can't be changed without them. Other
files outside specs/ have no owner, so Dependabot and AGENTS.md sync pull
requests don't need a code owner review.

Run from the repository root with full git history (not a shallow clone):

    python3 scripts/gen_codeowners.py            # write .github/CODEOWNERS
    python3 scripts/gen_codeowners.py --check    # fail if it is out of date

GITHUB_TOKEN or GH_TOKEN, when set, raises the GitHub API rate limit.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
import urllib.request
from pathlib import Path
from urllib.error import HTTPError, URLError

REPOSITORY = "tempoxyz/mpp-specs"
DEFAULT_OWNERS = ["@brendanjryan"]
OUTPUT = Path(".github/CODEOWNERS")
# Files that define the review policy; owned by DEFAULT_OWNERS so a change to who
# reviews specs needs their review too.
POLICY_FILES = ["/.github/CODEOWNERS", "/scripts/gen_codeowners.py"]
HEADER = (
    "# Generated by scripts/gen_codeowners.py from who submitted each spec.\n"
    "# Do not edit by hand: run 'make codeowners' and commit the result.\n"
)

NOREPLY = re.compile(r"^(?:\d+\+)?([A-Za-z0-9-]+)@users\.noreply\.github\.com$")
REVISION = re.compile(r"-\d{2}\.md$")
# Paths written into CODEOWNERS unescaped: no spaces, '#', '*' or other pattern syntax.
SAFE_PATH = re.compile(r"^specs/[A-Za-z0-9._/-]+\.md$")
# GitHub lookups that failed for a reason other than "commit not on GitHub yet".
LOOKUP_FAILURES: list[str] = []


def owner_pattern(path: str) -> str:
    """Return a CODEOWNERS pattern for a draft that survives revision bumps.

    '??' matches exactly the two-digit revision, so the rule doesn't also match a
    sibling draft whose name extends this one (draft-x-charge-delegated-00.md), as
    '*' would. CODEOWNERS doesn't support [0-9] character classes.
    """
    return "/" + REVISION.sub("-??.md", path)


def login_from_email(email: str) -> str | None:
    """Return the GitHub login in a noreply address, or None."""
    match = NOREPLY.match(email)
    return match.group(1) if match else None


def git(*args: str) -> str:
    return subprocess.run(["git", *args], check=True, capture_output=True, text=True).stdout


def revisions_glob(path: str) -> str:
    """Return a pathspec matching every revision of the draft at path, in any directory.

    Matching by draft name rather than with 'git log --follow' keeps ownership exact:
    --follow pairs files by content similarity, so a new spec copied from another, or a
    revision that rewrites most of its draft, would get the wrong submitter.
    """
    name = REVISION.sub("-[0-9][0-9].md", Path(path).name)
    return f":(glob)specs/**/{name}"


def first_commit(path: str) -> tuple[str, str] | None:
    """Return (sha, author email) of the commit that first added any revision of path."""
    log = git("log", "--diff-filter=A", "--format=%H %ae", "--", revisions_glob(path)).split("\n")
    lines = [line for line in log if line]
    if not lines:
        return None
    sha, email = lines[-1].split(" ", 1)
    return sha, email


def github(url: str) -> object:
    request = urllib.request.Request(f"https://api.github.com/{url}")
    request.add_header("Accept", "application/vnd.github+json")
    token = os.environ.get("GITHUB_TOKEN") or os.environ.get("GH_TOKEN")
    if token:
        request.add_header("Authorization", f"Bearer {token}")
    with urllib.request.urlopen(request, timeout=30) as response:
        return json.load(response)


def try_github(url: str) -> object | None:
    """Call the GitHub API; return None on failure.

    404/422 (a commit not pushed yet) is expected and only noted. Any other
    failure (bad token, rate limit, 5xx, network) is recorded in
    LOOKUP_FAILURES, and main() then refuses to write a CODEOWNERS file that
    would silently drop submitters.
    """
    try:
        return github(url)
    except HTTPError as error:
        if error.code in (404, 422):
            print(f"note: GitHub API {url}: commit not on GitHub yet", file=sys.stderr)
            return None
        reason = "rate limited: set GITHUB_TOKEN" if error.code in (403, 429) else f"HTTP {error.code}"
    except URLError as error:
        reason = str(error.reason)
    LOOKUP_FAILURES.append(f"{url}: {reason}")
    return None


def submitter(sha: str, email: str) -> str | None:
    """Return the login of whoever submitted the commit sha.

    Tries the pull request that merged it, then a noreply author email, then
    the commit's GitHub author. Returns None when none of them work, which
    leaves the entry to DEFAULT_OWNERS.
    """
    pulls = try_github(f"repos/{REPOSITORY}/commits/{sha}/pulls")
    if isinstance(pulls, list):
        merged = [pull for pull in pulls if pull.get("merged_at")] or pulls
        if merged and merged[0].get("user"):
            return merged[0]["user"]["login"]
    if login := login_from_email(email):
        return login
    commit = try_github(f"repos/{REPOSITORY}/commits/{sha}")
    author = commit.get("author") if isinstance(commit, dict) else None
    return author["login"] if author else None


def owner(path: str) -> str | None:
    """Return the submitter of path, or None for a file with no commit yet."""
    added = first_commit(path)
    if added is None:
        print(f"note: {path} has no commit yet; using default owners", file=sys.stderr)
        return None
    return submitter(*added)


def render(owners: dict[str, str | None], defaults: list[str]) -> str:
    """Render CODEOWNERS for {path: submitter login}."""
    # A default for drafts added after this file was generated; the per-draft rules
    # below come later, so they take precedence (CODEOWNERS uses the last match).
    lines = [HEADER]
    lines += [f"{path} {' '.join(defaults)}" for path in POLICY_FILES]
    lines.append(f"/specs/ {' '.join(defaults)}")
    for path in sorted(owners):
        login = owners[path]
        entry = [f"@{login}"] if login and f"@{login}" not in defaults else []
        lines.append(f"{owner_pattern(path)} {' '.join(entry + defaults)}")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if CODEOWNERS is out of date")
    args = parser.parse_args()

    if git("rev-parse", "--is-shallow-repository").strip() == "true":
        print("error: shallow clone; run 'git fetch --unshallow' first", file=sys.stderr)
        return 1

    paths = [p for p in git("ls-files", "specs/**.md").split("\n") if p]
    unsafe = [p for p in paths if not SAFE_PATH.match(p)]
    if unsafe:
        print(f"error: spec paths CODEOWNERS can't express safely: {unsafe}", file=sys.stderr)
        return 1
    owners = {path: owner(path) for path in paths}
    if LOOKUP_FAILURES:
        print("error: GitHub lookups failed; not writing CODEOWNERS:", file=sys.stderr)
        for failure in LOOKUP_FAILURES:
            print(f"  {failure}", file=sys.stderr)
        return 1
    content = render(owners, DEFAULT_OWNERS)

    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            print(f"error: {OUTPUT} is out of date; run 'make codeowners'", file=sys.stderr)
            return 1
        return 0

    OUTPUT.write_text(content)
    print(f"wrote {OUTPUT} ({len(paths)} specs)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
